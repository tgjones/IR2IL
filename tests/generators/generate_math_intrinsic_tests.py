#!/usr/bin/env python3
"""Generates tests/hand-written/math_intrinsics.ll: the floating point math intrinsics on float and double and on
vectors of them.

Exact intrinsics (`sqrt`, `fabs`, `ceil`, `copysign`, `fmuladd`) print the bit pattern of each result, a NaN as one
canonical value. The transcendental ones (`sin`, `cos`, `tan`, `asin`, `acos`, `atan`, `atan2`, `sinh`, `cosh`,
`tanh`, `exp`, `log`, `log10`, `pow`) print the bit pattern with the low bits of the mantissa cleared, because
the vector implementations of .NET and the native libm may differ in the last units of precision. `is.fpclass`
prints the result for every mask bit alone and for a few combinations.

Scalar tests run over every value of a table (and every pair, for the two-operand ones). Vector tests read the
table at every offset, so every lane meets different values.

There is no expected value here: the tests compare IR2IL's output with that of the same IR built by clang.

Usage:
    generate_math_intrinsic_tests.py            rewrite the file in tests/hand-written
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from generate_float_tests import (  # noqa: E402
    PRELUDE, array, loop, main_function, to_float, vtype, emit_lanes, vector_loads, repeated, ELEMENT_BITS,
)

VALUES = [0.0, -0.0, 0.5, -0.5, 1.0, -1.0, 2.0, 3.5, -2.75, 0.1, 10.0, -100.0, 12345.678, 1e-3, 700.0, -700.0,
          1e30, 5e-324, math.inf, -math.inf, math.nan]
# Multiplicands of `fmuladd`, whose products are exact in float and double (at most 12 significant bits each): LLVM may
# fuse the multiplication and the addition or not, and the results differ when the product is rounded, so a target
# that fuses (ARM64) and one that does not (x64 without FMA) would disagree on other values.
FMA_VALUES = [0.0, -0.0, 0.5, -0.5, 1.0, -1.0, 2.0, 3.5, -2.75, 10.0, -100.0, 700.0, -700.0, math.inf, -math.inf, math.nan]
# Powers and arctangents: moderate values only, so the results stay finite for most pairs.
EXACT_UNARY = ["sqrt", "fabs", "ceil"]
APPROX_UNARY = ["sin", "cos", "tan", "asin", "acos", "atan", "sinh", "cosh", "tanh", "exp", "log", "log10"]
EXACT_BINARY = ["copysign"]
APPROX_BINARY = ["atan2", "pow"]
SUFFIX = {"float": "f32", "double": "f64"}
MASK_BITS = {"float": 23, "double": 52}
KEEP_BITS = {"float": 13, "double": 28}

EMIT_APPROX = """
define void @emit_double_approx(double %v) {
  %bits = bitcast double %v to i64
  %nan = fcmp uno double %v, %v
  %masked = and i64 %bits, -268435456
  %out = select i1 %nan, i64 9221120237041090560, i64 %masked
  call void @emit_i64(i64 %out)
  ret void
}

define void @emit_float_approx(float %v) {
  %bits = bitcast float %v to i32
  %wide = zext i32 %bits to i64
  %nan = fcmp uno float %v, %v
  %masked = and i64 %wide, 4294959104
  %out = select i1 %nan, i64 2143289344, i64 %masked
  call void @emit_i64(i64 %out)
  ret void
}
"""


def shape_name(ty, n):
    return f"{ty}" if n == 1 else f"{ty}x{n}"


def llvm_type(ty, n):
    return ty if n == 1 else vtype(ty, n)


def intrinsic_name(op, ty, n):
    return f"llvm.{op}." + (SUFFIX[ty] if n == 1 else f"v{n}{SUFFIX[ty]}")


def result_lines(ty, n, emitter):
    if n == 1:
        return [f"call void @{emitter}_{ty}({ty} %r)"]
    return emit_lanes("r", ty, n, f"{emitter}_{ty}", "r")


def main():
    shapes = [(ty, n) for ty in ("double", "float") for n in (1, 2, 3, 4, 8, 16) if not (ty == "double" and n == 3)]
    values = {"double": VALUES, "float": [to_float(v) for v in VALUES]}
    parts = [
        "; Generated by tests/generators/generate_math_intrinsic_tests.py: the floating point math intrinsics on float,",
        "; double and vectors of them. See the generator for the details.",
        "",
        PRELUDE,
        EMIT_APPROX,
    ]
    for ty in ("double", "float"):
        parts.append(array(f"values_{ty}", ty, repeated(values[ty], 4)))
        parts.append(array(f"fma_values_{ty}", ty, repeated([to_float(v) if ty == "float" else v for v in FMA_VALUES], 16)))
    parts.append("")
    declared = set()
    functions, names = [], []

    def declare(op, ty, n, params):
        name = intrinsic_name(op, ty, n)
        if name not in declared:
            declared.add(name)
            t = llvm_type(ty, n)
            parts.append(f"declare {t} @{name}({', '.join([t] * params)})")

    count = len(VALUES)
    for ty, n in shapes:
        t = llvm_type(ty, n)
        align = ELEMENT_BITS[ty] // 8
        load_a = [f"%pa = getelementptr {ty}, ptr @values_{ty}, i64 %i", f"%a = load {t}, ptr %pa, align {align}"]
        load_b = [f"%pb = getelementptr {ty}, ptr @values_{ty}, i64 %j", f"%b = load {t}, ptr %pb, align {align}"]
        load_c = [f"%pc = getelementptr {ty}, ptr @values_{ty}, i64 %k", f"%c = load {t}, ptr %pc, align {align}"]
        for exact, ops in ((True, EXACT_UNARY), (False, APPROX_UNARY)):
            for op in ops:
                declare(op, ty, n, 1)
                name = f"run_{op}_{shape_name(ty, n)}"
                names.append(name)
                body = load_a + [f"%r = call {t} @{intrinsic_name(op, ty, n)}({t} %a)"] \
                    + result_lines(ty, n, "emit" if exact else "emit_approx_x")
                functions.append(loop(name, count, False, body))
        for exact, ops in ((True, EXACT_BINARY), (False, APPROX_BINARY)):
            for op in ops:
                declare(op, ty, n, 2)
                name = f"run_{op}_{shape_name(ty, n)}"
                names.append(name)
                body = load_a + load_b + [f"%r = call {t} @{intrinsic_name(op, ty, n)}({t} %a, {t} %b)"] \
                    + result_lines(ty, n, "emit" if exact else "emit_approx_x")
                functions.append(loop(name, count, True, body))
        # fmuladd: every pair of the exact multiplicands, with a few addends.
        declare("fmuladd", ty, n, 3)
        fma_a = [f"%pa = getelementptr {ty}, ptr @fma_values_{ty}, i64 %i", f"%a = load {t}, ptr %pa, align {align}"]
        fma_b = [f"%pb = getelementptr {ty}, ptr @fma_values_{ty}, i64 %j", f"%b = load {t}, ptr %pb, align {align}"]
        for addend in (0, 7, 12):
            name = f"run_fmuladd_{shape_name(ty, n)}_{addend}"
            names.append(name)
            body = fma_a + fma_b + [f"%pc = getelementptr {ty}, ptr @values_{ty}, i64 {addend}",
                                      f"%c = load {t}, ptr %pc, align {align}",
                                      f"%r = call {t} @{intrinsic_name('fmuladd', ty, n)}({t} %a, {t} %b, {t} %c)"] \
                + result_lines(ty, n, "emit")
            functions.append(loop(name, len(FMA_VALUES), True, body))
    # is.fpclass: scalars only.
    for ty in ("double", "float"):
        t = ty
        declared_name = f"llvm.is.fpclass.{SUFFIX[ty]}"
        parts.append(f"declare i1 @{declared_name}({t}, i32 immarg)")
        for mask in [1 << b for b in range(10)] + [3, 0x3c, 0x1c0, 0x3ff, 0x204, 0x60]:
            name = f"run_is_fpclass_{ty}_{mask}"
            names.append(name)
            body = [f"%pa = getelementptr {ty}, ptr @values_{ty}, i64 %i", f"%a = load {t}, ptr %pa",
                    f"%r = call i1 @{declared_name}({t} %a, i32 {mask})", "%w = zext i1 %r to i64",
                    "call void @emit_i64(i64 %w)"]
            functions.append(loop(name, count, False, body))
    parts.append("")
    for f in functions:
        parts += [f, ""]
    parts.append(main_function(names))
    text = "\n".join(parts) + "\n"
    # emit_approx_x_<ty> is the helper name used by the lane printer
    text = text.replace("emit_approx_x_double", "emit_double_approx").replace("emit_approx_x_float", "emit_float_approx")
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "hand-written", "math_intrinsics.ll")
    with open(out, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
