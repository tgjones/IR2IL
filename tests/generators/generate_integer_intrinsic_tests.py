#!/usr/bin/env python3
"""Generates tests/hand-written/integer_intrinsics.ll: `abs`, `smin`, `smax`, `umin`, `umax`, `scmp`, `ucmp`,
`ctpop` and `usub.sat` on scalars of i8, i16, i24, i32, i40 and i64 and on vectors of 8- to 64-bit lanes.

Every scalar test runs over every value of a table (every pair, for the two-operand ones): the limits, the
values around them and bit patterns. Each is run twice, with operands loaded from the table and with operands
computed by an `add`, whose result can have stray bits above the logical width (see "Normalisation" in
CLAUDE.md). `scmp` and `ucmp` return an i8, an i32 and an i64. The result is `zext`ed to i64 and printed. Vector
tests read the table at every offset, so every lane meets different values; `scmp`/`ucmp` have no vector form.
`abs` is always called with the poison flag clear, so the absolute value of the minimum is the minimum.

There is no expected value here: the tests compare IR2IL's output with that of the same IR built by clang.

Usage:
    generate_integer_intrinsic_tests.py            rewrite the file in tests/hand-written
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from generate_float_tests import PRELUDE, loop, main_function, int_array, signed_value  # noqa: E402

SCALAR_WIDTHS = [8, 16, 24, 32, 40, 64]
LANE_WIDTHS = [8, 16, 32, 64]
LANE_COUNTS = [2, 4, 8, 16]

UNARY = ["abs", "ctpop"]
BINARY = ["smin", "smax", "umin", "umax", "usub.sat"]
COMPARE = ["scmp", "ucmp"]


def values_for(bits):
    low, high = -(1 << (bits - 1)), (1 << (bits - 1)) - 1
    candidates = [0, 1, 2, 3, 5, 7, 8, 63, 64, 100, 127, 128, 255, 256, 1000, 0x5555555555555555, 0x2AAAAAAAAAAAAAAA,
                  0x0F0F0F0F0F0F0F0F, 0x00FF00FF00FF00FF, low, low + 1, high, high - 1, (1 << bits) - 1,
                  1 << (bits - 1), (1 << (bits - 2)), 0x8000, 0x7FFF, 0xFFFF, 0x80000000, 0x7FFFFFFF]
    result = []
    for c in candidates:
        for v in (c, -c):
            v = signed_value(v, bits)
            if v not in result:
                result.append(v)
    return result


def intrinsic(op, ty):
    return f"llvm.{op}.{ty}"


def printed(vector, ty, bits, lanes):
    """Lines that print the iN value or each lane of the vector, zero-extended to i64."""
    lines = []
    for k in range(lanes if lanes else 1):
        value = vector
        if lanes:
            lines.append(f"%x{k} = extractelement {ty} %{vector}, i32 {k}")
            value = f"x{k}"
        if bits == 64:
            lines.append(f"call void @emit_i64(i64 %{value})")
        else:
            lines.append(f"%w{k} = zext {ty.split(' x ')[-1].rstrip('>') if lanes else ty} %{value} to i64")
            lines.append(f"call void @emit_i64(i64 %w{k})")
    return lines


def main():
    parts = [
        "; Generated by tests/generators/generate_integer_intrinsic_tests.py: abs, smin, smax, umin, umax, scmp, ucmp,",
        "; ctpop and usub.sat on scalars and vectors. See the generator for the details.",
        "",
        PRELUDE,
    ]
    declared, functions, names, tables = set(), [], [], []

    def declare(op, ty, operands, result=None):
        name = f"llvm.{op}.{ty}" if result is None else f"llvm.{op}.{result}.{ty}"
        if name not in declared:
            declared.add(name)
            args = ", ".join([ty] * operands + (["i1 immarg"] if op == "abs" else []))
            parts.append(f"declare {result or ty} @{name}({args})")
        return name

    for bits in SCALAR_WIDTHS:
        ty = f"i{bits}"
        values = values_for(bits)
        tables.append(int_array(f"values_{ty}", bits, values))
        count = len(values)
        load_a = [f"%pa = getelementptr {ty}, ptr @values_{ty}, i64 %i", f"%a0 = load {ty}, ptr %pa"]
        load_b = [f"%pb = getelementptr {ty}, ptr @values_{ty}, i64 %j", f"%b0 = load {ty}, ptr %pb"]
        # Computed operands: the add can overflow the logical width and leave stray bits.
        computed = {
            "loaded": ([], load_a, load_b, ["%a = add {t} %a0, 0", "%b = add {t} %b0, 0"]),
            "computed": ([], load_a, load_b, ["%a = add {t} %a0, 1", "%b = add {t} %b0, -3"]),
        }
        for form, (_, la, lb, ops) in computed.items():
            ops = [o.format(t=ty) for o in ops]
            for op in UNARY:
                name = declare(op, ty, 1)
                extra = ", i1 false" if op == "abs" else ""
                names.append(f"run_{op.replace('.', '_')}_{ty}_{form}")
                body = la + ops[:1] + [f"%r = call {ty} @{name}({ty} %a{extra})"] + printed("r", ty, bits, 0)
                functions.append(loop(names[-1], count, False, body))
            for op in BINARY:
                name = declare(op, ty, 2)
                names.append(f"run_{op.replace('.', '_')}_{ty}_{form}")
                body = la + lb + ops + [f"%r = call {ty} @{name}({ty} %a, {ty} %b)"] + printed("r", ty, bits, 0)
                functions.append(loop(names[-1], count, True, body))
            for op in COMPARE:
                for result_bits in (8, 32, 64):
                    result = f"i{result_bits}"
                    name = declare(op, ty, 2, result)
                    names.append(f"run_{op}_{ty}_{result}_{form}")
                    body = la + lb + ops + [f"%r = call {result} @{name}({ty} %a, {ty} %b)"] + printed("r", result, result_bits, 0)
                    functions.append(loop(names[-1], count, True, body))

    for bits in LANE_WIDTHS:
        lane = f"i{bits}"
        values = values_for(bits)
        tables.append(int_array(f"values_{lane}_repeated", bits, values * (2 + 16 // len(values) + 1)))
        count = len(values)
        for lanes in LANE_COUNTS:
            ty = f"<{lanes} x {lane}>"
            if bits * lanes > 1024:
                continue
            align = bits // 8
            load_a = [f"%pa = getelementptr {lane}, ptr @values_{lane}_repeated, i64 %i",
                      f"%a = load {ty}, ptr %pa, align {align}"]
            load_b = [f"%pb = getelementptr {lane}, ptr @values_{lane}_repeated, i64 %j",
                      f"%b = load {ty}, ptr %pb, align {align}"]
            suffix = f"v{lanes}{lane}"
            for op in UNARY:
                intr = f"llvm.{op}.v{lanes}{lane}"
                if intr not in declared:
                    declared.add(intr)
                    flag = ", i1 immarg" if op == "abs" else ""
                    parts.append(f"declare {ty} @{intr}({ty}{flag})")
                extra = ", i1 false" if op == "abs" else ""
                names.append(f"run_{op}_{suffix}")
                body = load_a + [f"%r = call {ty} @{intr}({ty} %a{extra})"] + printed("r", ty, bits, lanes)
                functions.append(loop(names[-1], count, False, body))
            for op in BINARY:
                intr = f"llvm.{op}.v{lanes}{lane}"
                if intr not in declared:
                    declared.add(intr)
                    parts.append(f"declare {ty} @{intr}({ty}, {ty})")
                names.append(f"run_{op.replace('.', '_')}_{suffix}")
                body = load_a + load_b + [f"%r = call {ty} @{intr}({ty} %a, {ty} %b)"] + printed("r", ty, bits, lanes)
                functions.append(loop(names[-1], count, True, body))
    parts.append("")
    parts += tables
    parts.append("")
    for f in functions:
        parts += [f, ""]
    parts.append(main_function(names))
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "hand-written", "integer_intrinsics.ll")
    with open(out, "w") as f:
        f.write("\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
