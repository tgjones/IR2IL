#!/usr/bin/env python3
"""Generates tests/hand-written/vector_reductions.ll: `llvm.vector.reduce.*` on vectors of integers and floats.

Integer reductions (`add`, `mul`, `and`, `or`, `xor`, `smax`, `smin`, `umax`, `umin`) run over vectors of 8- to
64-bit lanes (2, 4, 8 and 16 lanes, and 3 lanes of i32). Floating point reductions (`fadd`, `fmul`) run over
`float` (2, 3, 4, 8, 16 lanes) and `double` (2, 4, 8 lanes), with a start value taken from the table and no fast-math
flags, so the lanes are combined in order, from the start value, and the result bits must match. Each vector is read
from a table at every offset, so every lane meets different values (and NaN, infinities and zeros of both signs
land in every position). The result is zero-extended (or its bits taken) and printed.

There is no expected value here: the tests compare IR2IL's output with that of the same IR built by clang.

Usage:
    generate_vector_reduce_tests.py            rewrite the file in tests/hand-written
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from generate_float_tests import PRELUDE, array, loop, main_function, int_array, to_float, ELEMENT_BITS, vtype  # noqa: E402
from generate_integer_intrinsic_tests import values_for  # noqa: E402

INT_OPS = ["add", "mul", "and", "or", "xor", "smax", "smin", "umax", "umin"]
FLOAT_OPS = ["fadd", "fmul"]
LANE_WIDTHS = [8, 16, 32, 64]
FLOAT_VALUES = [0.0, -0.0, 0.5, -0.5, 1.0, -1.0, 2.0, 3.5, -2.75, 0.1, 10.0, -100.0, 12345.678, 1e-3, 1e30,
                5e-324, math.inf, -math.inf, math.nan]


def int_shapes(bits):
    return [n for n in (2, 3, 4, 8, 16) if bits * n <= 512 and (n != 3 or bits == 32)]


def main():
    parts = [
        "; Generated by tests/generators/generate_vector_reduce_tests.py: llvm.vector.reduce.* on vectors of integers",
        "; and floats. See the generator for the details.",
        "",
        PRELUDE,
    ]
    declared, functions, names, tables = set(), [], [], []

    def declare(line_name, line):
        if line_name not in declared:
            declared.add(line_name)
            parts.append(line)

    for bits in LANE_WIDTHS:
        lane = f"i{bits}"
        values = values_for(bits)
        tables.append(int_array(f"values_{lane}", bits, values * 3))
        count = len(values)
        for n in int_shapes(bits):
            ty = f"<{n} x {lane}>"
            load = [f"%pa = getelementptr {lane}, ptr @values_{lane}, i64 %i",
                    f"%a = load {ty}, ptr %pa, align {bits // 8}"]
            for op in INT_OPS:
                intr = f"llvm.vector.reduce.{op}.v{n}{lane}"
                declare(intr, f"declare {lane} @{intr}({ty})")
                name = f"run_reduce_{op}_v{n}{lane}"
                names.append(name)
                body = load + [f"%r = call {lane} @{intr}({ty} %a)"]
                if bits == 64:
                    body.append("call void @emit_i64(i64 %r)")
                else:
                    body += [f"%w = zext {lane} %r to i64", "call void @emit_i64(i64 %w)"]
                functions.append(loop(name, count, False, body))

    for ty, widths in (("double", (2, 4, 8)), ("float", (2, 3, 4, 8, 16))):
        values = FLOAT_VALUES if ty == "double" else [to_float(v) for v in FLOAT_VALUES]
        tables.append(array(f"values_{ty}", ty, values * 3))
        count = len(FLOAT_VALUES)
        suffix = "f64" if ty == "double" else "f32"
        for n in widths:
            vt = vtype(ty, n)
            align = ELEMENT_BITS[ty] // 8
            load = [f"%pa = getelementptr {ty}, ptr @values_{ty}, i64 %i", f"%a = load {vt}, ptr %pa, align {align}",
                    f"%ps = getelementptr {ty}, ptr @values_{ty}, i64 %j", f"%s = load {ty}, ptr %ps"]
            for op in FLOAT_OPS:
                intr = f"llvm.vector.reduce.{op}.v{n}{suffix}"
                declare(intr, f"declare {ty} @{intr}({ty}, {vt})")
                name = f"run_reduce_{op}_v{n}{ty}"
                names.append(name)
                body = load + [f"%r = call {ty} @{intr}({ty} %s, {vt} %a)", f"call void @emit_{ty}({ty} %r)"]
                functions.append(loop(name, count, True, body))

    parts.append("")
    parts += tables
    parts.append("")
    for f in functions:
        parts += [f, ""]
    parts.append(main_function(names))
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "hand-written", "vector_reductions.ll")
    with open(out, "w") as f:
        f.write("\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
