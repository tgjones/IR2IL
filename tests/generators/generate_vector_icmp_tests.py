#!/usr/bin/env python3
"""Generates tests/hand-written/vector_icmp.ll.

Every integer predicate (eq, ne, ugt, uge, ult, ule, sgt, sge, slt, sle) on vectors of i8, i16, i32 and i64
lanes, over every pair of values from a set that includes the signed/unsigned boundaries (0, 1, 2^(w-1)-1,
2^(w-1), 2^w-1). The result mask is read with `bitcast <N x i1> to iN` and compared with the mask computed here.
A second check per width and predicate feeds the comparison to a vector `select`, which takes another code path
(the comparison is used as it is, without being narrowed to <N x i1> first).

`main` returns the 1-based number of the first (width, predicate) group that returned a wrong result, or 0.

Usage:
    generate_vector_icmp_tests.py            rewrite tests/hand-written/vector_icmp.ll
"""

import os

# (lane bits, lanes). Not <2 x i64>: <2 x i1> is a Vector16, which has no ExtractMostSignificantBits.
WIDTHS = [(8, 16), (16, 8), (32, 4), (64, 4)]
PREDICATES = ["eq", "ne", "ugt", "uge", "ult", "ule", "sgt", "sge", "slt", "sle"]


def signed(value, bits):
    return value - (1 << bits) if value >= 1 << (bits - 1) else value


def holds(predicate, a, b, bits):
    sa, sb = signed(a, bits), signed(b, bits)
    return {
        "eq": a == b, "ne": a != b,
        "ugt": a > b, "uge": a >= b, "ult": a < b, "ule": a <= b,
        "sgt": sa > sb, "sge": sa >= sb, "slt": sa < sb, "sle": sa <= sb,
    }[predicate]


def vector(values, bits):
    return f"<{len(values)} x i{bits}> <" + ", ".join(f"i{bits} {signed(v, bits)}" for v in values) + ">"


def main():
    out = [
        "; exit-code: 0",
        "; Generated by tests/generators/generate_vector_icmp_tests.py: every integer predicate on vectors of",
        "; i8/i16/i32/i64 lanes over values around the signed and unsigned boundaries, both read as a mask",
        "; (bitcast <N x i1> to iN) and used as the condition of a vector select. main returns the 1-based number",
        "; of the first group that returned a wrong result (see the generator), or 0.",
        "",
    ]
    groups = []  # (title, calls) where each call is (function, args, expected, type)
    for bits, lanes in WIDTHS:
        values = sorted({0, 1, 2, (1 << (bits - 1)) - 1, 1 << (bits - 1), (1 << bits) - 2, (1 << bits) - 1})
        pairs = [(a, b) for a in values for b in values]
        chunks = [pairs[i:i + lanes] for i in range(0, len(pairs), lanes)]
        for chunk in chunks:  # pad the last chunk by repeating its first pair
            chunk.extend([chunk[0]] * (lanes - len(chunk)))
        for predicate in PREDICATES:
            name = f"i{bits}_{predicate}"
            out += [
                f"define i{lanes} @mask_{name}(<{lanes} x i{bits}> %a, <{lanes} x i{bits}> %b) {{",
                f"  %c = icmp {predicate} <{lanes} x i{bits}> %a, %b",
                f"  %m = bitcast <{lanes} x i1> %c to i{lanes}",
                f"  ret i{lanes} %m",
                "}",
                f"define <{lanes} x i{bits}> @select_{name}(<{lanes} x i{bits}> %a, <{lanes} x i{bits}> %b) {{",
                f"  %c = icmp {predicate} <{lanes} x i{bits}> %a, %b",
                f"  %r = select <{lanes} x i1> %c, <{lanes} x i{bits}> %a, <{lanes} x i{bits}> %b",
                "  ret <%d x i%d> %%r" % (lanes, bits),
                "}",
                "",
            ]
            calls = []
            for chunk in chunks:
                a = [p[0] for p in chunk]
                b = [p[1] for p in chunk]
                expected_mask = sum(1 << i for i, (x, y) in enumerate(chunk) if holds(predicate, x, y, bits))
                calls.append(("mask", name, bits, lanes, a, b, expected_mask))
                expected_select = [x if holds(predicate, x, y, bits) else y for x, y in chunk]
                calls.append(("select", name, bits, lanes, a, b, expected_select))
            groups.append((f"{predicate} on <{lanes} x i{bits}>", calls))

    out.append("define i32 @main() {")
    n = 0
    for gid, (title, calls) in enumerate(groups, start=1):
        out.append(f"  ; {gid}: {title}")
        for kind, name, bits, lanes, a, b, expected in calls:
            n += 1
            va, vb = vector(a, bits), vector(b, bits)
            if kind == "mask":
                out.append(f"  %r{n} = call i{lanes} @mask_{name}({va}, {vb})")
                out.append(f"  %ok{n} = icmp eq i{lanes} %r{n}, {signed(expected, lanes)}")
            else:
                out.append(f"  %r{n} = call <{lanes} x i{bits}> @select_{name}({va}, {vb})")
                out.append(f"  %c{n} = icmp eq <{lanes} x i{bits}> %r{n}, {vector(expected, bits)[len(f'<{lanes} x i{bits}> '):]}")
                out.append(f"  %m{n} = bitcast <{lanes} x i1> %c{n} to i{lanes}")
                out.append(f"  %ok{n} = icmp eq i{lanes} %m{n}, -1")
            out.append(f"  br i1 %ok{n}, label %next{n}, label %fail{gid}")
            out.append(f"next{n}:")
    out.append("  ret i32 0")
    for gid in range(1, len(groups) + 1):
        out.append(f"fail{gid}:")
        out.append(f"  ret i32 {gid}")
    out.append("}")

    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "hand-written", "vector_icmp.ll")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {os.path.normpath(path)}: {len(groups)} groups, {n} checks")


main()
