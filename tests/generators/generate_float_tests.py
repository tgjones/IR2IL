#!/usr/bin/env python3
"""Generates tests/hand-written/float_arithmetic.ll, float_conversions.ll and float_fcmp.ll, and the vector_float_*.ll files.

float_arithmetic.ll: `fadd`, `fsub`, `fmul`, `fdiv`, `frem` and `fneg` on `float` and `double`, over every pair
of values from a set that includes zeros of both signs, denormals, the largest finite values, infinities and a
NaN. Each result is printed as its bit pattern (a NaN as one canonical value, because its payload and sign are
not defined), so a difference in the sign of a zero is seen too.

float_conversions.ll: `fptosi`, `fptoui` (to i8, i16, i32 and i64), `fpext` and `fptrunc`. The inputs of
`fptosi`/`fptoui` are the values whose truncation fits the destination type: anything else is poison, and clang
and IR2IL may legitimately differ. `fptrunc` includes overflow to infinity, underflow to a denormal or zero,
and ties that must round to even.

float_fcmp.ll: all 16 `fcmp` predicates on `float` and `double` over every pair of the same values (so NaN
against everything, and -0.0 against 0.0), used three ways: stored as an `i1` (`zext`ed and printed), as the
condition of a `br`, and as the condition of a `select`. Each way takes a different path in the emitter.

vector_float_fcmp.ll, vector_float_arithmetic.ll and vector_float_conversions.ll: the same operations on vectors
of float and double (2, 3, 4, 8 and 16 lanes, which covers Vector64 to Vector512 and the padded <3 x float>).
Each vector is read from a table of the values above at every offset, so each lane meets different values and
NaN lands in every lane position. `fcmp` is read as a mask (`bitcast <N x i1>` to an integer), as a `select`
condition and as a `sext` to integer lanes. The results are printed lane by lane.

There is no expected value here: the tests compare IR2IL's output with that of the same IR built by clang.

Usage:
    generate_float_tests.py            rewrite the files in tests/hand-written
"""
import math
import os
import struct

DOUBLE_VALUES = [
    0.0, -0.0, 1.0, -1.0, 0.5, 3.5, -2.75, 1e300, -1e300, 5e-324, 1.7976931348623157e308,
    math.inf, -math.inf, math.nan,
]
FLOAT_VALUES = [
    0.0, -0.0, 1.0, -1.0, 0.5, 3.5, -2.75, 1e30, -1e30, 1.401298464324817e-45, 3.4028234663852886e38,
    math.inf, -math.inf, math.nan,
]


def hex_double(v):
    """A constant for a double, or for a float that is exactly representable as a double."""
    if math.isnan(v):
        return "0x7FF8000000000000"
    return "0x%016X" % struct.unpack(">Q", struct.pack(">d", v))[0]


def to_float(v):
    return struct.unpack(">f", struct.pack(">f", v))[0] if not math.isinf(v) and abs(v) < 3.4028235677973366e38 else (
        math.copysign(math.inf, v))


def array(name, ty, values):
    elements = ", ".join(f"{ty} {hex_double(v)}" for v in values)
    return f"@{name} = private constant [{len(values)} x {ty}] [{elements}]"


PRELUDE = """declare i32 @printf(ptr, ...)

@fmt = private constant [6 x i8] c"%llx\\0A\\00"

define void @emit_i64(i64 %v) {
  call i32 (ptr, ...) @printf(ptr @fmt, i64 %v)
  ret void
}

define void @emit_double(double %v) {
  %bits = bitcast double %v to i64
  %nan = fcmp uno double %v, %v
  %out = select i1 %nan, i64 9221120237041090560, i64 %bits
  call void @emit_i64(i64 %out)
  ret void
}

define void @emit_float(float %v) {
  %bits = bitcast float %v to i32
  %wide = zext i32 %bits to i64
  %nan = fcmp uno float %v, %v
  %out = select i1 %nan, i64 2143289344, i64 %wide
  call void @emit_i64(i64 %out)
  ret void
}
"""


def loop(name, count, nested, body):
    """A function that runs `body` for each i (and each j when nested) below `count`; the body gets %i, %j."""
    lines = [f"define void @{name}() {{", "entry:", "  %pi = alloca i64", "  %pj = alloca i64",
             "  store i64 0, ptr %pi", "  br label %outer", "outer:", "  %i = load i64, ptr %pi",
             f"  %oc = icmp slt i64 %i, {count}", "  br i1 %oc, label %inner.init, label %done",
             "inner.init:", "  store i64 0, ptr %pj", "  br label %inner", "inner:", "  %j = load i64, ptr %pj"]
    if nested:
        lines += [f"  %ic = icmp slt i64 %j, {count}", "  br i1 %ic, label %body, label %outer.next"]
    else:
        lines += ["  br label %body"]
    lines += ["body:"] + ["  " + b for b in body]
    if nested:
        lines += ["  %jn = add i64 %j, 1", "  store i64 %jn, ptr %pj", "  br label %inner"]
    else:
        lines += ["  br label %outer.next"]
    lines += ["outer.next:", "  %in = add i64 %i, 1", "  store i64 %in, ptr %pi", "  br label %outer",
              "done:", "  ret void", "}"]
    return "\n".join(lines)


def main_function(names):
    calls = "\n".join(f"  call void @{n}()" for n in names)
    return f"define i32 @main() {{\n{calls}\n  ret i32 0\n}}"


def arithmetic():
    parts = [
        "; Generated by tests/generators/generate_float_tests.py: fadd, fsub, fmul, fdiv, frem and fneg on float and",
        "; double over zeros, denormals, extremes, infinities and NaN. See the generator for the details.",
        "",
        PRELUDE,
        array("values_double", "double", DOUBLE_VALUES),
        array("values_float", "float", [to_float(v) for v in FLOAT_VALUES]),
        "",
    ]
    names = []
    for ty, count in (("double", len(DOUBLE_VALUES)), ("float", len(FLOAT_VALUES))):
        load = [f"%pa = getelementptr {ty}, ptr @values_{ty}, i64 %i", f"%a = load {ty}, ptr %pa"]
        load_b = [f"%pb = getelementptr {ty}, ptr @values_{ty}, i64 %j", f"%b = load {ty}, ptr %pb"]
        for op in ("fadd", "fsub", "fmul", "fdiv", "frem"):
            name = f"run_{op}_{ty}"
            names.append(name)
            parts.append(loop(name, count, True, load + load_b + [f"%r = {op} {ty} %a, %b", f"call void @emit_{ty}({ty} %r)"]))
            parts.append("")
        name = f"run_fneg_{ty}"
        names.append(name)
        parts.append(loop(name, count, False, load + [f"%r = fneg {ty} %a", f"call void @emit_{ty}({ty} %r)"]))
        parts.append("")
    parts.append(main_function(names))
    return "\n".join(parts) + "\n"


CONVERSION_CANDIDATES = [
    0.0, -0.0, 0.5, -0.5, 1.0, -1.0, 1.5, -1.5, 127.0, 127.9, -128.0, -128.9, 128.0, 255.0, 255.9, -129.0, 256.0,
    32767.0, 32767.9, -32768.0, -32768.9, 32768.0, 65535.0, 65535.9, 65536.0, 16777215.0, 16777216.0, 16777217.0,
    2147483646.0, 2147483647.0, 2147483647.9, -2147483648.0, -2147483648.9, 2147483648.0, 4294967294.0, 4294967295.0, 4294967295.9,
    4294967296.0, 9223372036854774784.0, -9223372036854775808.0, 18446744073709549568.0,
]
FPTRUNC_CANDIDATES = [
    0.0, -0.0, 1.0, -1.5, 3.4028234663852886e38, 3.4028235677973366e38, 1e39, -1e39, 1e300, 1e-40, 1e-46, -1e-46,
    1.401298464324817e-45, 16777217.0, 1.0000000298023224, 1.0000000894069672, math.inf, -math.inf, math.nan,
]
FPEXT_CANDIDATES = [
    0.0, -0.0, 1.0, -1.5, 3.4028234663852886e38, 1.401298464324817e-45, 1.1754943508222875e-38,
    16777216.0, math.inf, -math.inf, math.nan,
]


def conversions():
    parts = [
        "; Generated by tests/generators/generate_float_tests.py: fptosi, fptoui, fpext and fptrunc over values that",
        "; are not poison (the inputs of fptosi/fptoui fit the destination type). See the generator for the details.",
        "",
        PRELUDE,
    ]
    names = []
    tables = []
    functions = []
    for src in ("double", "float"):
        for signed in (True, False):
            for bits in (8, 16, 32, 64):
                values = []
                for v in CONVERSION_CANDIDATES:
                    v = to_float(v) if src == "float" else v
                    if math.isinf(v):
                        continue
                    t = math.trunc(v)
                    low, high = (-(1 << (bits - 1)), (1 << (bits - 1)) - 1) if signed else (0, (1 << bits) - 1)
                    if low <= t <= high and v not in values:
                        values.append(v)
                op = "fptosi" if signed else "fptoui"
                suffix = f"{op}_{src}_i{bits}"
                tables.append(array(f"values_{suffix}", src, values))
                body = [f"%p = getelementptr {src}, ptr @values_{suffix}, i64 %i", f"%a = load {src}, ptr %p",
                        f"%r = {op} {src} %a to i{bits}"]
                if bits < 64:
                    body.append(f"%w = {'sext' if signed else 'zext'} i{bits} %r to i64")
                    body.append("call void @emit_i64(i64 %w)")
                else:
                    body.append("call void @emit_i64(i64 %r)")
                functions.append(loop(f"run_{suffix}", len(values), False, body))
                names.append(f"run_{suffix}")
    for name, src, dst, op, candidates in (
        ("fpext_float_double", "float", "double", "fpext", FPEXT_CANDIDATES),
        ("fptrunc_double_float", "double", "float", "fptrunc", FPTRUNC_CANDIDATES),
    ):
        values = [to_float(v) if src == "float" else v for v in candidates]
        tables.append(array(f"values_{name}", src, values))
        body = [f"%p = getelementptr {src}, ptr @values_{name}, i64 %i", f"%a = load {src}, ptr %p",
                f"%r = {op} {src} %a to {dst}", f"call void @emit_{dst}({dst} %r)"]
        functions.append(loop(f"run_{name}", len(values), False, body))
        names.append(f"run_{name}")
    parts += tables + [""]
    for f in functions:
        parts += [f, ""]
    parts.append(main_function(names))
    return "\n".join(parts) + "\n"


PREDICATES = ["false", "oeq", "ogt", "oge", "olt", "ole", "one", "ord", "uno", "ueq", "ugt", "uge", "ult", "ule",
              "une", "true"]


def fcmp():
    parts = [
        "; Generated by tests/generators/generate_float_tests.py: every fcmp predicate on float and double, stored,",
        "; as a branch condition and as a select condition. See the generator for the details.",
        "",
        PRELUDE,
        array("values_double", "double", DOUBLE_VALUES),
        array("values_float", "float", [to_float(v) for v in FLOAT_VALUES]),
        "",
    ]
    names = []
    for ty, count in (("double", len(DOUBLE_VALUES)), ("float", len(FLOAT_VALUES))):
        load = [f"%pa = getelementptr {ty}, ptr @values_{ty}, i64 %i", f"%a = load {ty}, ptr %pa",
                f"%pb = getelementptr {ty}, ptr @values_{ty}, i64 %j", f"%b = load {ty}, ptr %pb"]
        for predicate in PREDICATES:
            compare = f"%c = fcmp {predicate} {ty} %a, %b"
            forms = {
                "stored": [compare, "%w = zext i1 %c to i64", "call void @emit_i64(i64 %w)"],
                "branch": [compare, "br i1 %c, label %yes, label %no", "yes:", "call void @emit_i64(i64 1)",
                           "br label %merge", "no:", "call void @emit_i64(i64 0)", "br label %merge", "merge:"],
                "select": [compare, "%s = select i1 %c, i64 7, i64 9", "call void @emit_i64(i64 %s)"],
            }
            for form, body in forms.items():
                name = f"run_fcmp_{predicate}_{ty}_{form}"
                names.append(name)
                parts += [loop(name, count, True, load + body), ""]
    parts.append(main_function(names))
    return "\n".join(parts) + "\n"


VECTOR_TYPES = [("double", 2), ("double", 4), ("double", 8), ("float", 2), ("float", 3), ("float", 4),
                ("float", 8), ("float", 16)]
ELEMENT_BITS = {"double": 64, "float": 32}


def repeated(values, lanes):
    """Enough copies of `values` that a vector of `lanes` can start at any index of the original."""
    return values * (2 + lanes // len(values))


def vtype(ty, n):
    return f"<{n} x {ty}>"


def emit_lanes(vector, ty, n, emitter, prefix, convert=None):
    """Lines that print each lane of the vector `%vector` with `emitter`, after `convert` (an instruction
    template such as 'sext {ty} {value} to i64') when the lane is not printed as it is."""
    lines = []
    for k in range(n):
        lines.append(f"%{prefix}x{k} = extractelement {vtype(ty, n)} %{vector}, i32 {k}")
        value = f"%{prefix}x{k}"
        if convert and ty == "i64":
            lines.append(f"call void @emit_i64(i64 {value})")
        elif convert:
            lines.append(f"%{prefix}w{k} = " + convert.format(ty=ty, value=value))
            value = f"%{prefix}w{k}"
            lines.append(f"call void @emit_i64(i64 {value})")
        else:
            lines.append(f"call void @{emitter}({ty} {value})")
    return lines


def vector_loads(ty, n, table, nested):
    lines = [f"%pa = getelementptr {ty}, ptr @{table}, i64 %i", f"%a = load {vtype(ty, n)}, ptr %pa, align {ELEMENT_BITS[ty] // 8}"]
    if nested:
        lines += [f"%pb = getelementptr {ty}, ptr @{table}, i64 %j",
                  f"%b = load {vtype(ty, n)}, ptr %pb, align {ELEMENT_BITS[ty] // 8}"]
    return lines


def vector_fcmp():
    parts = [
        "; Generated by tests/generators/generate_float_tests.py: every fcmp predicate on vectors of float and double,",
        "; read as a mask, as a select condition and as a sext. See the generator for the details.",
        "",
        PRELUDE,
    ]
    names = []
    for ty, values in (("double", DOUBLE_VALUES), ("float", [to_float(v) for v in FLOAT_VALUES])):
        parts.append(array(f"values_{ty}", ty, repeated(values, 16)))
    parts.append("")
    for ty, n in VECTOR_TYPES:
        count = len(DOUBLE_VALUES)
        bits = ELEMENT_BITS[ty]
        loads = vector_loads(ty, n, f"values_{ty}", True)
        for predicate in PREDICATES:
            compare = f"%c = fcmp {predicate} {vtype(ty, n)} %a, %b"
            forms = {
                "mask": [compare, f"%m = bitcast <{n} x i1> %c to i{n}", f"%w = zext i{n} %m to i64",
                         "call void @emit_i64(i64 %w)"],
                "select": [compare, f"%s = select <{n} x i1> %c, {vtype(ty, n)} %a, {vtype(ty, n)} %b"]
                          + emit_lanes("s", ty, n, f"emit_{ty}", "s"),
                "sext": [compare, f"%x = sext <{n} x i1> %c to <{n} x i{bits}>"]
                        + emit_lanes("x", f"i{bits}", n, None, "r", "sext {ty} {value} to i64"),
            }
            for form, body in forms.items():
                name = f"run_fcmp_{predicate}_{ty}x{n}_{form}"
                names.append(name)
                parts += [loop(name, count, True, loads + body), ""]
    parts.append(main_function(names))
    return "\n".join(parts) + "\n"


def vector_arithmetic():
    parts = [
        "; Generated by tests/generators/generate_float_tests.py: fadd, fsub, fmul, fdiv, frem and fneg on vectors of",
        "; float and double. See the generator for the details.",
        "",
        PRELUDE,
    ]
    names = []
    for ty, values in (("double", DOUBLE_VALUES), ("float", [to_float(v) for v in FLOAT_VALUES])):
        parts.append(array(f"values_{ty}", ty, repeated(values, 16)))
    parts.append("")
    for ty, n in VECTOR_TYPES:
        count = len(DOUBLE_VALUES)
        for op in ("fadd", "fsub", "fmul", "fdiv", "frem"):
            name = f"run_{op}_{ty}x{n}"
            names.append(name)
            body = vector_loads(ty, n, f"values_{ty}", True) + [f"%r = {op} {vtype(ty, n)} %a, %b"] + emit_lanes("r", ty, n, f"emit_{ty}", "r")
            parts += [loop(name, count, True, body), ""]
        name = f"run_fneg_{ty}x{n}"
        names.append(name)
        body = vector_loads(ty, n, f"values_{ty}", False) + [f"%r = fneg {vtype(ty, n)} %a"] + emit_lanes("r", ty, n, f"emit_{ty}", "r")
        parts += [loop(name, count, False, body), ""]
    parts.append(main_function(names))
    return "\n".join(parts) + "\n"


def int_array(name, bits, values):
    elements = ", ".join(f"i{bits} {v}" for v in values)
    return f"@{name} = private constant [{len(values)} x i{bits}] [{elements}]"


def signed_value(v, bits):
    v &= (1 << bits) - 1
    return v - (1 << bits) if v >= 1 << (bits - 1) else v


def vector_conversions():
    parts = [
        "; Generated by tests/generators/generate_float_tests.py: fptosi, fptoui, sitofp, uitofp, fpext and fptrunc on",
        "; vectors, over values that are not poison (the inputs of fptosi/fptoui fit the destination type). See the",
        "; generator for the details.",
        "",
        PRELUDE,
    ]
    tables, functions, names = [], [], []

    def add(name, loop_count, body):
        functions.append(loop(f"run_{name}", loop_count, False, body))
        names.append(f"run_{name}")

    # float -> integer
    for src, n, bits in (("float", 4, 32), ("float", 2, 32), ("float", 8, 32), ("double", 2, 64), ("double", 4, 64),
                         ("float", 4, 16), ("double", 2, 32)):
        for signed in (True, False):
            values = []
            for v in CONVERSION_CANDIDATES:
                v = to_float(v) if src == "float" else v
                if math.isinf(v):
                    continue
                low, high = (-(1 << (bits - 1)), (1 << (bits - 1)) - 1) if signed else (0, (1 << bits) - 1)
                if low <= math.trunc(v) <= high and v not in values:
                    values.append(v)
            op = "fptosi" if signed else "fptoui"
            suffix = f"{op}_{src}x{n}_i{bits}"
            tables.append(array(f"values_{suffix}", src, repeated(values, n)))
            body = vector_loads(src, n, f"values_{suffix}", False) + [f"%r = {op} {vtype(src, n)} %a to <{n} x i{bits}>"]
            body += emit_lanes("r", f"i{bits}", n, None, "r", ("sext" if signed else "zext") + " {ty} {value} to i64")
            add(suffix, len(values), body)

    # integer -> float
    for dst, n, bits in (("float", 4, 32), ("float", 2, 32), ("float", 8, 32), ("double", 2, 64), ("double", 4, 64),
                         ("float", 4, 16), ("double", 2, 32)):
        raw = [0, 1, -1, 2, 100, -100, 127, -128, 255, 32767, -32768, 65535, 16777216, 16777217, 2147483647,
               -2147483648, 4294967295, 9007199254740993, 9223372036854775807, -9223372036854775808,
               18446744073709551615]
        for signed in (True, False):
            values = []
            for v in raw:
                if signed and -(1 << (bits - 1)) <= v < (1 << (bits - 1)) or not signed and 0 <= v < (1 << bits) or (
                        not signed and v < 0 and -v <= 1 << (bits - 1)):
                    sv = signed_value(v, bits)
                    if sv not in values:
                        values.append(sv)
            op = "sitofp" if signed else "uitofp"
            suffix = f"{op}_i{bits}x{n}_{dst}"
            tables.append(int_array(f"values_{suffix}", bits, repeated(values, n)))
            body = [f"%p = getelementptr i{bits}, ptr @values_{suffix}, i64 %i",
                    f"%a = load <{n} x i{bits}>, ptr %p, align {bits // 8}",
                    f"%r = {op} <{n} x i{bits}> %a to {vtype(dst, n)}"] + emit_lanes("r", dst, n, f"emit_{dst}", "r")
            add(suffix, len(values), body)

    # float <-> double
    for name, src, dst, op, n, candidates in (
        ("fpext_floatx2_doublex2", "float", "double", "fpext", 2, FPEXT_CANDIDATES),
        ("fpext_floatx4_doublex4", "float", "double", "fpext", 4, FPEXT_CANDIDATES),
        ("fptrunc_doublex2_floatx2", "double", "float", "fptrunc", 2, FPTRUNC_CANDIDATES),
        ("fptrunc_doublex4_floatx4", "double", "float", "fptrunc", 4, FPTRUNC_CANDIDATES),
    ):
        values = [to_float(v) if src == "float" else v for v in candidates]
        tables.append(array(f"values_{name}", src, repeated(values, n)))
        body = vector_loads(src, n, f"values_{name}", False) + [
            f"%r = {op} {vtype(src, n)} %a to {vtype(dst, n)}"] + emit_lanes("r", dst, n, f"emit_{dst}", "r")
        add(name, len(values), body)

    parts += tables + [""]
    for f in functions:
        parts += [f, ""]
    parts.append(main_function(names))
    return "\n".join(parts) + "\n"


def main():
    directory = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "hand-written")
    for file_name, text in (("float_arithmetic.ll", arithmetic()), ("float_conversions.ll", conversions()),
                             ("float_fcmp.ll", fcmp()),
                             ("vector_float_fcmp.ll", vector_fcmp()),
                             ("vector_float_arithmetic.ll", vector_arithmetic()),
                             ("vector_float_conversions.ll", vector_conversions())):
        with open(os.path.join(directory, file_name), "w") as f:
            f.write(text)


if __name__ == "__main__":
    main()
