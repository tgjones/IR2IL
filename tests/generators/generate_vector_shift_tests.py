#!/usr/bin/env python3
"""Generates tests/hand-written/vector_variable_shifts.ll.

`shl`, `lshr` and `ashr` of vectors of i8, i16, i32 and i64 lanes (2 to 32 lanes, so Vector64 up to Vector1024, and
the padded <2 x i8>, <4 x i8> and <2 x i16>) by a vector of counts that are not all the same. The values and the
counts are read from tables in memory, so the shift can't be folded to a uniform constant, and every pair of table
windows is used: each lane meets different values and different counts. The counts are always below the lane width,
as a larger one is poison. The values include 0, 1, -1, both limits and alternating bit patterns. Each lane of the
result is printed (sign-extended to i64).

There is no expected value here: the tests compare IR2IL's output with that of the same IR built by clang.

Usage:
    generate_vector_shift_tests.py            rewrite tests/hand-written/vector_variable_shifts.ll
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from generate_float_tests import PRELUDE, loop, main_function, int_array, repeated, vtype, emit_lanes  # noqa: E402

SHAPES = {8: [2, 4, 8, 16, 32], 16: [2, 4, 8, 16], 32: [2, 4, 8, 16], 64: [2, 4, 8, 16]}
COUNTS = {8: [0, 1, 2, 3, 4, 5, 6, 7], 16: [0, 1, 3, 7, 8, 12, 14, 15], 32: [0, 1, 5, 8, 16, 23, 30, 31],
          64: [0, 1, 7, 16, 32, 33, 62, 63]}


def signed(v, bits):
    v &= (1 << bits) - 1
    return v - (1 << bits) if v >= 1 << (bits - 1) else v


def values(bits):
    alternating = int("01" * (bits // 2), 2)
    return [signed(v, bits) for v in (0, 1, -1, 1 << (bits - 1), (1 << (bits - 1)) - 1, alternating,
                                      alternating << 1, 0x1234567890ABCDEF)]


def main():
    parts = [
        "; Generated by tests/generators/generate_vector_shift_tests.py: shl, lshr and ashr of vectors by vectors of",
        "; different counts. See the generator for the details.",
        "",
        PRELUDE,
    ]
    tables, functions, names = [], [], []
    for bits, shapes in SHAPES.items():
        vals, counts = values(bits), COUNTS[bits]
        assert len(vals) == len(counts)
        for lanes in shapes:
            tables.append(int_array(f"values_i{bits}x{lanes}", bits, repeated(vals, lanes)))
            tables.append(int_array(f"counts_i{bits}x{lanes}", bits, repeated(counts, lanes)))
            for op in ("shl", "lshr", "ashr"):
                name = f"{op}_i{bits}x{lanes}"
                align = bits // 8
                body = [f"%pa = getelementptr i{bits}, ptr @values_i{bits}x{lanes}, i64 %i",
                        f"%a = load {vtype(f'i{bits}', lanes)}, ptr %pa, align {align}",
                        f"%pb = getelementptr i{bits}, ptr @counts_i{bits}x{lanes}, i64 %j",
                        f"%b = load {vtype(f'i{bits}', lanes)}, ptr %pb, align {align}",
                        f"%r = {op} {vtype(f'i{bits}', lanes)} %a, %b"]
                body += emit_lanes("r", f"i{bits}", lanes, None, "r", "sext {ty} {value} to i64")
                functions.append(loop(f"run_{name}", len(vals), True, body))
                names.append(f"run_{name}")
    parts += tables + [""]
    for f in functions:
        parts += [f, ""]
    parts.append(main_function(names))
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "hand-written", "vector_variable_shifts.ll")
    with open(path, "w") as f:
        f.write("\n".join(parts) + "\n")
    print(f"wrote {os.path.normpath(path)}: {len(names)} functions")


if __name__ == "__main__":
    main()
