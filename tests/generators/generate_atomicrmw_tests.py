#!/usr/bin/env python3
"""Generates tests/hand-written/atomicrmw_integers.ll and atomicrmw_floats.ll.

atomicrmw_integers.ll:
`atomicrmw` with every integer operation (`xchg`, `add`, `sub`, `and`, `nand`, `or`, `xor`, `max`, `min`, `umax`,
`umin`) on i8, i16, i32 and i64 (i128 needs `cmpxchg16b` or a libcall, so it is not covered). Each function takes
every pair (a, b) from a table of limits and bit patterns, stores a in a stack slot, runs the operation with b, and
prints the value it returned (which must be the old value, a) and the value left in memory, both sign-extended to
i64. Three more shapes per width: a constant operand (1 and -1, which a compiler may turn into an increment or a
decrement), a result that is not used, and, for i32 `add`, every memory ordering, `volatile` and a `syncscope`.

atomicrmw_floats.ll: `xchg`, `fadd`, `fsub`, `fmax` and `fmin` on float and double, over every pair of the values of
generate_float_tests.py (zeros, denormals, extremes, infinities, a NaN), a constant operand, and an unused result.
Results are printed as bit patterns (a NaN as one canonical value). `fmax`/`fmin` return the other operand when one is
a NaN, and may return either zero when the operands are +0.0 and -0.0, so -0.0 is left out of their tables.

There is no expected value here: the tests compare IR2IL's output with that of the same IR built by clang.

Usage:
    generate_atomicrmw_tests.py            rewrite the two files in tests/hand-written
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from generate_float_tests import (PRELUDE, DOUBLE_VALUES, FLOAT_VALUES, array, to_float, loop, main_function,  # noqa: E402
                                  int_array, signed_value)

WIDTHS = [8, 16, 32, 64]
OPS = ["xchg", "add", "sub", "and", "nand", "or", "xor", "max", "min", "umax", "umin"]
ORDERINGS = ["monotonic", "acquire", "release", "acq_rel", "seq_cst"]


def values(bits):
    alternating = int("01" * (bits // 2), 2)
    raw = [0, 1, -1, 2, 1 << (bits - 1), (1 << (bits - 1)) - 1, alternating, alternating << 1, 0x1234567890ABCDEF]
    return [signed_value(v, bits) for v in raw]


def sext(ty_bits, name):
    """Lines that sign-extend %name to i64 as %name.w (nothing to do for i64)."""
    if ty_bits == 64:
        return [], name
    return [f"%{name}.w = sext i{ty_bits} %{name} to i64"], f"{name}.w"


def emit(bits, *names):
    lines = []
    for n in names:
        extra, w = sext(bits, n)
        lines += extra + [f"call void @emit_i64(i64 %{w})"]
    return lines


def integers():
    parts = [
        "; Generated by tests/generators/generate_atomicrmw_tests.py: every integer atomicrmw operation on i8 to i64,",
        "; over pairs of limits and bit patterns. See the generator for the details.",
        "",
        PRELUDE,
    ]
    names, functions = [], []
    for bits in WIDTHS:
        vals = values(bits)
        ty = f"i{bits}"
        parts.append(int_array(f"values_{ty}", bits, vals))
        align = bits // 8
        for op in OPS:
            slot = ["%slot = alloca " + ty + ", align " + str(align),
                    f"%pa = getelementptr {ty}, ptr @values_{ty}, i64 %i", f"%a = load {ty}, ptr %pa",
                    f"store {ty} %a, ptr %slot, align {align}"]
            # Every pair.
            name = f"run_{op}_{ty}"
            body = slot + [f"%pb = getelementptr {ty}, ptr @values_{ty}, i64 %j", f"%b = load {ty}, ptr %pb",
                           f"%old = atomicrmw {op} ptr %slot, {ty} %b seq_cst, align {align}",
                           f"%new = load {ty}, ptr %slot, align {align}"] + emit(bits, "old", "new")
            functions.append(loop(name, len(vals), True, body))
            names.append(name)
            # A constant operand.
            for label, const in (("one", 1), ("minus_one", -1)):
                name = f"run_{op}_{ty}_{label}"
                body = slot + [f"%old = atomicrmw {op} ptr %slot, {ty} {const} seq_cst, align {align}",
                               f"%new = load {ty}, ptr %slot, align {align}"] + emit(bits, "old", "new")
                functions.append(loop(name, len(vals), False, body))
                names.append(name)
            # The result is not used.
            name = f"run_{op}_{ty}_unused"
            body = slot + [f"%pb = getelementptr {ty}, ptr @values_{ty}, i64 %j", f"%b = load {ty}, ptr %pb",
                           f"atomicrmw {op} ptr %slot, {ty} %b seq_cst, align {align}",
                           f"%new = load {ty}, ptr %slot, align {align}"] + emit(bits, "new")
            functions.append(loop(name, len(vals), True, body))
            names.append(name)

    # Orderings, volatile and syncscope, on i32 add.
    variants = [(o, f"{o}") for o in ORDERINGS]
    variants += [("volatile", "seq_cst", "volatile "), ("syncscope", 'syncscope("singlethread") seq_cst')]
    for variant in variants:
        label = variant[0]
        ordering = variant[1]
        prefix = variant[2] if len(variant) > 2 else ""
        name = f"run_add_i32_{label}"
        body = ["%slot = alloca i32, align 4", "%pa = getelementptr i32, ptr @values_i32, i64 %i",
                "%a = load i32, ptr %pa", "store i32 %a, ptr %slot, align 4",
                f"%old = atomicrmw {prefix}add ptr %slot, i32 7 {ordering}, align 4",
                "%new = load i32, ptr %slot, align 4"] + emit(32, "old", "new")
        functions.append(loop(name, len(values(32)), False, body))
        names.append(name)

    parts.append("")
    for f in functions:
        parts += [f, ""]
    parts.append(main_function(names))
    return "\n".join(parts) + "\n", len(names)


FLOAT_OPS = ["xchg", "fadd", "fsub", "fmax", "fmin"]


def floats():
    parts = [
        "; Generated by tests/generators/generate_atomicrmw_tests.py: xchg, fadd, fsub, fmax and fmin on float and double",
        "; over zeros, denormals, extremes, infinities and NaN. See the generator for the details.",
        "",
        PRELUDE,
    ]
    names, functions = [], []
    for ty, table in (("float", [to_float(v) for v in FLOAT_VALUES]), ("double", DOUBLE_VALUES)):
        # fmax and fmin may return either zero for +0.0 and -0.0, so their table has no -0.0.
        no_negative_zero = [v for v in table if str(v) != "-0.0"]
        parts.append(array(f"values_{ty}", ty, table))
        parts.append(array(f"values_{ty}_no_negative_zero", ty, no_negative_zero))
        align = 4 if ty == "float" else 8
        for op in FLOAT_OPS:
            suffix = "_no_negative_zero" if op in ("fmax", "fmin") else ""
            values = no_negative_zero if suffix else table
            slot = [f"%slot = alloca {ty}, align {align}",
                    f"%pa = getelementptr {ty}, ptr @values_{ty}{suffix}, i64 %i", f"%a = load {ty}, ptr %pa",
                    f"store {ty} %a, ptr %slot, align {align}"]
            operand = [f"%pb = getelementptr {ty}, ptr @values_{ty}{suffix}, i64 %j", f"%b = load {ty}, ptr %pb"]
            result = ["%new = load " + f"{ty}, ptr %slot, align {align}"]
            shown = [f"call void @emit_{ty}({ty} %old)", f"call void @emit_{ty}({ty} %new)"]
            name = f"run_{op}_{ty}"
            body = slot + operand + [f"%old = atomicrmw {op} ptr %slot, {ty} %b seq_cst, align {align}"] + result + shown
            functions.append(loop(name, len(values), True, body))
            names.append(name)
            for label, const in (("one", "1.0"), ("minus_one", "-1.0")):
                name = f"run_{op}_{ty}_{label}"
                body = slot + [f"%old = atomicrmw {op} ptr %slot, {ty} {const} seq_cst, align {align}"] + result + shown
                functions.append(loop(name, len(values), False, body))
                names.append(name)
            name = f"run_{op}_{ty}_unused"
            body = slot + operand + [f"atomicrmw {op} ptr %slot, {ty} %b seq_cst, align {align}"] + result + shown[1:]
            functions.append(loop(name, len(values), True, body))
            names.append(name)
    parts.append("")
    for f in functions:
        parts += [f, ""]
    parts.append(main_function(names))
    return "\n".join(parts) + "\n", len(names)


def main():
    directory = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "hand-written")
    for file, (text, count) in (("atomicrmw_integers.ll", integers()), ("atomicrmw_floats.ll", floats())):
        path = os.path.join(directory, file)
        with open(path, "w") as f:
            f.write(text)
        print(f"wrote {os.path.normpath(path)}: {count} functions")


if __name__ == "__main__":
    main()
