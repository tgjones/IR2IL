#!/usr/bin/env python3
"""Generates tests/hand-written/half_arithmetic.ll, half_fcmp.ll, half_conversions.ll and half_memory.ll.

Scalar `half`: `fadd`, `fsub`, `fmul`, `fdiv`, `frem` and `fneg` over every pair of a table of half values (zeros of
both signs, the smallest denormal, the largest denormal and normal, 65504, infinities, NaN); all 16 `fcmp`
predicates over every pair, stored as an `i1`, as a `br` condition and as a `select` condition; `fpext`,
`fptrunc` (ties, overflow, underflow, and a double that rounds the wrong way when it is rounded to float first),
`fptosi`, `fptoui`, `sitofp`, `uitofp` and `bitcast`; and loads, stores, allocas, globals, constant arrays and
structs, calls, `select`, `phi` and `undef`/`poison`. A NaN result is printed as one canonical value, because its
payload is not defined. Inputs of `fptosi`/`fptoui` and `sitofp`/`uitofp` stay where the result is defined.

There is no expected value here: the tests compare IR2IL's output with that of the same IR built by clang.

Usage:
    generate_half_tests.py            rewrite the files in tests/hand-written
"""
import math
import os
import struct

HALF_BITS = [
    0x0000, 0x8000, 0x3C00, 0xBC00, 0x3800, 0x4300, 0xC180, 0x7BFF, 0xFBFF, 0x0400, 0x0001, 0x03FF, 0x8001,
    0x7C00, 0xFC00, 0x7E00, 0x63D0, 0x2E66, 0x5640, 0x6400,
]


def half_value(bits):
    return struct.unpack("<e", struct.pack("<H", bits))[0]


def half_const(bits):
    return "0xH%04X" % bits


def table(name, ty, items):
    return f"@{name} = private constant [{len(items)} x {ty}] [{', '.join(f'{ty} {i}' for i in items)}]"


PRELUDE = """declare i32 @printf(ptr, ...)

@fmt = private constant [6 x i8] c"%llx\\0A\\00"

define void @emit_i64(i64 %v) {
  call i32 (ptr, ...) @printf(ptr @fmt, i64 %v)
  ret void
}

define void @emit_half(half %v) {
  %bits = bitcast half %v to i16
  %wide = zext i16 %bits to i64
  %nan = fcmp uno half %v, %v
  %out = select i1 %nan, i64 32256, i64 %wide
  call void @emit_i64(i64 %out)
  ret void
}

define void @emit_float(float %v) {
  %bits = bitcast float %v to i32
  %wide = zext i32 %bits to i64
  %nan = fcmp uno float %v, %v
  %out = select i1 %nan, i64 2143289344, i64 %wide
  call void @emit_i64(i64 %out)
  ret void
}

define void @emit_double(double %v) {
  %bits = bitcast double %v to i64
  %nan = fcmp uno double %v, %v
  %out = select i1 %nan, i64 9221120237041090560, i64 %bits
  call void @emit_i64(i64 %out)
  ret void
}
"""

HALF_TABLE = table("halfs", "half", [half_const(b) for b in HALF_BITS])
N = len(HALF_BITS)


def pair_loop(name, body):
    """A function that runs `body` for every pair (%a, %b) of the half table."""
    return f"""define void @{name}() {{
entry:
  %i = alloca i32
  %j = alloca i32
  store i32 0, ptr %i
  br label %outer
outer:
  %iv = load i32, ptr %i
  %ic = icmp slt i32 %iv, {N}
  br i1 %ic, label %inner_init, label %done
inner_init:
  store i32 0, ptr %j
  br label %inner
inner:
  %jv = load i32, ptr %j
  %jc = icmp slt i32 %jv, {N}
  br i1 %jc, label %work, label %outer_next
work:
  %ia = sext i32 %iv to i64
  %ja = sext i32 %jv to i64
  %pa = getelementptr half, ptr @halfs, i64 %ia
  %pb = getelementptr half, ptr @halfs, i64 %ja
  %a = load half, ptr %pa
  %b = load half, ptr %pb
{body}
  %jn = add i32 %jv, 1
  store i32 %jn, ptr %j
  br label %inner
outer_next:
  %in = add i32 %iv, 1
  store i32 %in, ptr %i
  br label %outer
done:
  ret void
}}
"""


def single_loop(name, table_name, ty, count, body, elem_label="x"):
    return f"""define void @{name}() {{
entry:
  %i = alloca i32
  store i32 0, ptr %i
  br label %loop
loop:
  %iv = load i32, ptr %i
  %c = icmp slt i32 %iv, {count}
  br i1 %c, label %work, label %done
work:
  %ia = sext i32 %iv to i64
  %p = getelementptr {ty}, ptr @{table_name}, i64 %ia
  %x = load {ty}, ptr %p
{body}
  %n = add i32 %iv, 1
  store i32 %n, ptr %i
  br label %loop
done:
  ret void
}}
"""


def write(name, header, parts):
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "hand-written", name)
    with open(path, "w") as f:
        f.write(f"; Generated by tests/generators/generate_half_tests.py: {header}\n\n")
        f.write("\n".join(parts))


def arithmetic():
    parts = [PRELUDE, HALF_TABLE]
    calls = []
    for op in ["fadd", "fsub", "fmul", "fdiv", "frem"]:
        parts.append(pair_loop(f"run_{op}", f"  %r = {op} half %a, %b\n  call void @emit_half(half %r)"))
        calls.append(f"  call void @run_{op}()")
    parts.append(single_loop("run_fneg", "halfs", "half", N, "  %r = fneg half %x\n  call void @emit_half(half %r)"))
    calls.append("  call void @run_fneg()")
    # Constant operands, and an unused result.
    parts.append("""define void @run_constants() {
  %a = fadd half 0xH3C00, 0xH4000
  call void @emit_half(half %a)
  %b = fmul half 0xH4300, 0xHC000
  call void @emit_half(half %b)
  %c = fdiv half 0xH3C00, 0xH4200
  call void @emit_half(half %c)
  %unused = fadd half 0xH3C00, 0xH3C00
  ret void
}
""")
    calls.append("  call void @run_constants()")
    parts.append("define i32 @main() {\n" + "\n".join(calls) + "\n  ret i32 0\n}\n")
    write("half_arithmetic.ll", "fadd, fsub, fmul, fdiv, frem and fneg on half, over every pair of a table.", parts)


PREDICATES = ["false", "oeq", "ogt", "oge", "olt", "ole", "one", "ord", "uno", "ueq", "ugt", "uge", "ult", "ule", "une", "true"]


def fcmp():
    parts = [PRELUDE, HALF_TABLE]
    calls = []
    for p in PREDICATES:
        body = (
            f"  %c = fcmp {p} half %a, %b\n  %z = zext i1 %c to i64\n  call void @emit_i64(i64 %z)\n"
            f"  %c2 = fcmp {p} half %a, %b\n  br i1 %c2, label %t_{p}, label %f_{p}\n"
            f"t_{p}:\n  call void @emit_i64(i64 1)\n  br label %m_{p}\n"
            f"f_{p}:\n  call void @emit_i64(i64 0)\n  br label %m_{p}\n"
            f"m_{p}:\n"
            f"  %c3 = fcmp {p} half %a, %b\n  %s = select i1 %c3, i64 1, i64 0\n  call void @emit_i64(i64 %s)"
        )
        parts.append(pair_loop(f"run_{p}", body))
        calls.append(f"  call void @run_{p}()")
    parts.append("define i32 @main() {\n" + "\n".join(calls) + "\n  ret i32 0\n}\n")
    write("half_fcmp.ll", "all 16 fcmp predicates on half over every pair, stored, as a branch and as a select.", parts)


def conversions():
    parts = [PRELUDE, HALF_TABLE]
    calls = []

    # fpext
    parts.append(single_loop("run_fpext_float", "halfs", "half", N, "  %r = fpext half %x to float\n  call void @emit_float(float %r)"))
    parts.append(single_loop("run_fpext_double", "halfs", "half", N, "  %r = fpext half %x to double\n  call void @emit_double(double %r)"))
    calls += ["  call void @run_fpext_float()", "  call void @run_fpext_double()"]

    # fptrunc from float
    floats = [0.0, -0.0, 1.0, -1.0, 65504.0, 65519.0, -65519.0, 65520.0, 1e-8, 2.9802322387695312e-08,
              5.960464477539063e-08, 8.940696716308594e-08, 1.0009765625, 1.00048828125, 1.0014648437,
              6.103515625e-05, 6.097555160522461e-05, 3.4e38, -3.4e38, math.inf, -math.inf, math.nan, 0.1, 3.14159274]
    float_items = ["0x%016X" % struct.unpack(">Q", struct.pack(">d", struct.unpack(">f", struct.pack(">f", v))[0] if abs(v) < 3.5e38 else v))[0] if not math.isnan(v) else "0x7FF8000000000000" for v in floats]
    parts.append(table("floats", "float", float_items))
    parts.append(single_loop("run_fptrunc_float", "floats", "float", len(floats), "  %r = fptrunc float %x to half\n  call void @emit_half(half %r)"))
    calls.append("  call void @run_fptrunc_float()")

    # fptrunc from double: includes values that round differently when rounded to float first.
    doubles = floats + [1.0 + 2.0**-11 + 2.0**-40, 1.0 + 2.0**-11 - 2.0**-40, 65520.0 - 2.0**-30, 2.0**-25 + 2.0**-60,
                        2.0**-25 - 2.0**-60, 1e300, -1e300, 5e-324]
    double_items = ["0x%016X" % struct.unpack(">Q", struct.pack(">d", v))[0] if not math.isnan(v) else "0x7FF8000000000000" for v in doubles]
    parts.append(table("doubles", "double", double_items))
    parts.append(single_loop("run_fptrunc_double", "doubles", "double", len(doubles), "  %r = fptrunc double %x to half\n  call void @emit_half(half %r)"))
    calls.append("  call void @run_fptrunc_double()")

    # fptosi / fptoui: inputs whose truncation fits the destination.
    signed_small = [0x0000, 0x8000, 0x3C00, 0xBC00, 0x3800, 0x4300, 0xC180, 0x5640, 0xD640, 0x57FF, 0xD800]
    signed_big = signed_small + [0x7BFF, 0xFBFF, 0x77FF]
    unsigned_small = [0x0000, 0x8000, 0x3C00, 0x3800, 0x4300, 0x5640, 0x57FF, 0x5A40, 0x5BFF]
    unsigned_big = unsigned_small + [0x7BFF, 0x77FF]
    cases = [
        ("i8", "fptosi", "s8", signed_small), ("i16", "fptosi", "s16", signed_big[:signed_big.index(0x7BFF)] + [0x77FF]),
        ("i32", "fptosi", "s32", signed_big), ("i64", "fptosi", "s64", signed_big),
        ("i8", "fptoui", "u8", unsigned_small), ("i16", "fptoui", "u16", unsigned_big),
        ("i32", "fptoui", "u32", unsigned_big), ("i64", "fptoui", "u64", unsigned_big),
    ]
    for ity, op, tag, bits in cases:
        parts.append(table(f"in_{tag}", "half", [half_const(b) for b in bits]))
        parts.append(single_loop(
            f"run_{tag}", f"in_{tag}", "half", len(bits),
            f"  %r = {op} half %x to {ity}\n"
            + (f"  %w = {'sext' if op == 'fptosi' else 'zext'} {ity} %r to i64\n" if ity != "i64" else "  %w = add i64 %r, 0\n")
            + "  call void @emit_i64(i64 %w)"))
        calls.append(f"  call void @run_{tag}()")

    # sitofp / uitofp: stay below 65520, where the result would overflow.
    ints = [0, 1, -1, 2047, 2048, 2049, 2050, 2051, 2052, 4095, 4097, 4099, 32767, 32768, 65503, 65504, 65505, 65519,
            -2049, -2051, -32768, -65504, -65519, 100, 127, -128, 255]
    for ity, op, lo, hi in [("i8", "sitofp", -128, 127), ("i16", "sitofp", -32768, 32767), ("i32", "sitofp", -65519, 65519),
                            ("i64", "sitofp", -65519, 65519), ("i8", "uitofp", 0, 255), ("i16", "uitofp", 0, 65519),
                            ("i32", "uitofp", 0, 65519), ("i64", "uitofp", 0, 65519)]:
        vals = sorted({v for v in ints if lo <= v <= hi})
        tag = f"{op}_{ity}"
        parts.append(table(f"in_{tag}", ity, [str(v) for v in vals]))
        parts.append(single_loop(
            f"run_{tag}", f"in_{tag}", ity, len(vals),
            f"  %r = {op} {ity} %x to half\n  call void @emit_half(half %r)"))
        calls.append(f"  call void @run_{tag}()")

    # bitcast
    parts.append(single_loop("run_bitcast", "halfs", "half",  N,
                             "  %b = bitcast half %x to i16\n  %w = zext i16 %b to i64\n  call void @emit_i64(i64 %w)\n"
                             "  %back = bitcast i16 %b to half\n  call void @emit_half(half %back)"))
    calls.append("  call void @run_bitcast()")

    parts.append("define i32 @main() {\n" + "\n".join(calls) + "\n  ret i32 0\n}\n")
    write("half_conversions.ll", "fpext, fptrunc, fptosi, fptoui, sitofp, uitofp and bitcast on half.", parts)


MEMORY = PRELUDE + """
%mixed = type { half, i8, half, float, half }
@global_half = global half 0xH4300
@global_zero = global half zeroinitializer
@const_half = private constant half 0xHBC00
@const_array = private constant [5 x half] [half 0xH3C00, half 0xH4000, half 0xH4200, half 0xH4400, half 0xH4500]
@mixed_global = global %mixed { half 0xH3C00, i8 7, half 0xH4000, float 2.5, half 0xHC200 }
@mixed_array = global [3 x %mixed] [%mixed { half 0xH3C00, i8 1, half 0xH4000, float 1.5, half 0xH4200 }, %mixed zeroinitializer, %mixed { half 0xH4400, i8 3, half 0xH4500, float -1.5, half 0xH4600 }]

define half @pass(half %x) {
  ret half %x
}

define half @sum_args(half %a, i32 %i, half %b, double %d, half %c, float %f, half %e) {
  %s1 = fadd half %a, %b
  %s2 = fadd half %s1, %c
  %s3 = fadd half %s2, %e
  %fi = sitofp i32 %i to half
  %s4 = fadd half %s3, %fi
  %fd = fptrunc double %d to half
  %s5 = fadd half %s4, %fd
  %ff = fptrunc float %f to half
  %s6 = fadd half %s5, %ff
  ret half %s6
}

define half @pick(i1 %c, half %x) {
  %r = select i1 %c, half %x, half undef
  %s = select i1 %c, half %r, half poison
  ret half %s
}

define half @loop_sum(i32 %n) {
entry:
  br label %loop
loop:
  %i = phi i32 [ 0, %entry ], [ %in, %loop ]
  %acc = phi half [ 0xH0000, %entry ], [ %next, %loop ]
  %x = sitofp i32 %i to half
  %next = fadd half %acc, %x
  %in = add i32 %i, 1
  %c = icmp slt i32 %in, %n
  br i1 %c, label %loop, label %done
done:
  ret half %next
}

define %mixed @make_mixed(half %a, half %b) {
  %m0 = insertvalue %mixed undef, half %a, 0
  %m1 = insertvalue %mixed %m0, i8 9, 1
  %m2 = insertvalue %mixed %m1, half %b, 2
  %m3 = insertvalue %mixed %m2, float 0.5, 3
  %m4 = insertvalue %mixed %m3, half 0xH3C00, 4
  ret %mixed %m4
}

define void @emit_mixed(ptr %p) {
  %p0 = getelementptr %mixed, ptr %p, i32 0, i32 0
  %v0 = load half, ptr %p0
  call void @emit_half(half %v0)
  %p1 = getelementptr %mixed, ptr %p, i32 0, i32 1
  %v1 = load i8, ptr %p1
  %w1 = zext i8 %v1 to i64
  call void @emit_i64(i64 %w1)
  %p2 = getelementptr %mixed, ptr %p, i32 0, i32 2
  %v2 = load half, ptr %p2
  call void @emit_half(half %v2)
  %p3 = getelementptr %mixed, ptr %p, i32 0, i32 3
  %v3 = load float, ptr %p3
  call void @emit_float(float %v3)
  %p4 = getelementptr %mixed, ptr %p, i32 0, i32 4
  %v4 = load half, ptr %p4
  call void @emit_half(half %v4)
  ret void
}

define i32 @main() {
  ; alloca, store and load, with a neighbour that must stay untouched
  %buf = alloca [4 x half]
  %b0 = getelementptr half, ptr %buf, i64 0
  %b1 = getelementptr half, ptr %buf, i64 1
  %b2 = getelementptr half, ptr %buf, i64 2
  %b3 = getelementptr half, ptr %buf, i64 3
  store i64 -1, ptr %buf
  store half 0xH3C00, ptr %b1
  store half undef, ptr %b2
  store half 0xH4000, ptr %b2
  %l0 = load half, ptr %b0
  call void @emit_half(half %l0)
  %l1 = load half, ptr %b1
  call void @emit_half(half %l1)
  %l2 = load half, ptr %b2
  call void @emit_half(half %l2)
  %l3 = load half, ptr %b3
  call void @emit_half(half %l3)

  ; globals and constants
  %g = load half, ptr @global_half
  call void @emit_half(half %g)
  store half 0xH5640, ptr @global_zero
  %z = load half, ptr @global_zero
  call void @emit_half(half %z)
  %c = load half, ptr @const_half
  call void @emit_half(half %c)
  %a4 = getelementptr [5 x half], ptr @const_array, i64 0, i64 4
  %e4 = load half, ptr %a4
  call void @emit_half(half %e4)
  %sum = call half @loop_sum(i32 30)
  call void @emit_half(half %sum)

  ; structs and arrays of structs, in memory and by value
  call void @emit_mixed(ptr @mixed_global)
  %m1 = getelementptr [3 x %mixed], ptr @mixed_array, i64 0, i64 1
  call void @emit_mixed(ptr %m1)
  %m2 = getelementptr [3 x %mixed], ptr @mixed_array, i64 0, i64 2
  call void @emit_mixed(ptr %m2)
  %made = call %mixed @make_mixed(half 0xH4800, half 0xHC800)
  %slot = alloca %mixed
  store %mixed %made, ptr %slot
  call void @emit_mixed(ptr %slot)
  %fromgep = extractvalue %mixed %made, 2
  call void @emit_half(half %fromgep)

  ; calls
  %p = call half @pass(half 0xH4D00)
  call void @emit_half(half %p)
  %s = call half @sum_args(half 0xH3C00, i32 3, half 0xH4000, double 2.5, half 0xH4200, float -0.25, half 0xH4400)
  call void @emit_half(half %s)
  %t = call i1 @pass_bool(i1 true)
  %pk = call half @pick(i1 %t, half 0xH4B00)
  call void @emit_half(half %pk)

  ; a half passed to a variadic function is promoted to double
  %wide = fpext half 0xH4900 to double
  call i32 (ptr, ...) @printf(ptr @fmt_d, double %wide)
  ret i32 0
}

@fmt_d = private constant [4 x i8] c"%f\\0A\\00"

define i1 @pass_bool(i1 %x) {
  ret i1 %x
}
"""


def memory():
    write("half_memory.ll", "loads, stores, alloca, globals, constant arrays, structs, calls, select, phi and undef of half.", [MEMORY])


if __name__ == "__main__":
    arithmetic()
    fcmp()
    conversions()
    memory()
